/**
 * Turning database and network failures into something an administrator can act
 * on — without leaking SQL text, column names, credential fragments or internal
 * stack traces to the browser.
 *
 * The mapping is driven by PostgreSQL SQLSTATE codes, which are stable, rather
 * than by string-matching error messages.
 */

export type AppErrorKind =
  | "permission"
  | "not_found"
  | "conflict"
  | "validation"
  | "schema"
  | "network"
  | "unknown";

export interface AppError {
  kind: AppErrorKind;
  /** Safe to show in the UI. */
  message: string;
  /** Guidance for an operator/developer; shown in a collapsed detail block. */
  hint?: string;
}

interface PgLikeError {
  code?: string;
  message?: string;
  details?: string | null;
  hint?: string | null;
}

function asPgError(error: unknown): PgLikeError {
  if (typeof error === "object" && error !== null) {
    const candidate = error as Record<string, unknown>;
    return {
      code: typeof candidate.code === "string" ? candidate.code : undefined,
      message: typeof candidate.message === "string" ? candidate.message : undefined,
      details: typeof candidate.details === "string" ? candidate.details : null,
      hint: typeof candidate.hint === "string" ? candidate.hint : null,
    };
  }
  if (typeof error === "string") return { message: error };
  return {};
}

/**
 * Constraint messages written by our own migrations are already phrased for a
 * human ("You cannot deactivate your own administrator account."). Anything
 * generated by PostgreSQL itself is not, so it is discarded.
 */
function isAuthoredMessage(message: string | undefined): boolean {
  if (!message) return false;
  if (/^new row for relation|^duplicate key value|^update or delete on table|^insert or update on table|^null value in column|^value too long|^invalid input syntax/i.test(message)) {
    return false;
  }
  return /^[A-Z].*[.!?]$/.test(message.trim());
}

export function toAppError(error: unknown): AppError {
  const pg = asPgError(error);
  const code = pg.code ?? "";

  switch (code) {
    case "42501":
      return {
        kind: "permission",
        message: "You do not have permission to perform this action.",
        hint: "Your role does not include this capability. Ask a super admin if you need it.",
      };

    case "23505":
      return {
        kind: "conflict",
        message: isAuthoredMessage(pg.message)
          ? pg.message!
          : "A record with the same unique value already exists (for example a duplicate code or key).",
        hint: "Change the conflicting value and try again.",
      };

    case "23503":
      return {
        kind: "conflict",
        message: isAuthoredMessage(pg.message)
          ? pg.message!
          : "This record is still referenced by other records.",
        hint: "Deactivate it instead of deleting, so historical data keeps its references.",
      };

    case "23514":
    case "22001":
    case "22P02":
      return {
        kind: "validation",
        message: isAuthoredMessage(pg.message)
          ? pg.message!
          : "Some of the supplied values were rejected by a database rule.",
        hint: pg.details ?? undefined,
      };

    case "23502":
      return {
        kind: "validation",
        message: "A required field was missing.",
        hint: pg.message,
      };

    // The schema has not been applied, or is older than this build.
    case "42P01":
      return {
        kind: "schema",
        message: "This table does not exist in the connected database.",
        hint: "Apply the SQL migrations in supabase/migrations to the Supabase project, then reload.",
      };

    case "42703":
      return {
        kind: "schema",
        message: "The database schema does not match what this page expects.",
        hint: "A column is missing. Apply the latest migration in supabase/migrations.",
      };

    case "42883":
      return {
        kind: "schema",
        message: "A required database function is missing.",
        hint: "Apply the SQL migrations in supabase/migrations, which define the helper functions.",
      };

    default:
      break;
  }

  const message = pg.message ?? "";

  if (/permission denied for (table|function|schema)/i.test(message)) {
    return {
      kind: "permission",
      message: "You do not have permission to perform this action.",
    };
  }

  if (/relation .* does not exist|could not find the table/i.test(message)) {
    return {
      kind: "schema",
      message: "This table does not exist in the connected database.",
      hint: "Apply the SQL migrations in supabase/migrations to the Supabase project.",
    };
  }

  if (/fetch failed|network|ENOTFOUND|ECONNREFUSED|ETIMEDOUT|aborted/i.test(message)) {
    return {
      kind: "network",
      message: "Could not reach the database.",
      hint: "Check your network connection and that NEXT_PUBLIC_SUPABASE_URL is correct.",
    };
  }

  if (/row-level security|violates row-level security/i.test(message)) {
    return {
      kind: "permission",
      message: "The database refused this change under its row level security rules.",
      hint: "Your role may not write to this table.",
    };
  }

  return {
    kind: "unknown",
    message: "Something went wrong while talking to the database.",
    hint: message || undefined,
  };
}

/** True when the failure is a missing table/column rather than a normal error. */
export function isSchemaIssue(error: unknown): boolean {
  const pg = asPgError(error);
  return pg.code === "42P01" || pg.code === "42703" || pg.code === "42883";
}

export function isPermissionIssue(error: unknown): boolean {
  const pg = asPgError(error);
  return pg.code === "42501" || /row-level security/i.test(pg.message ?? "");
}

export function isUniqueViolation(error: unknown, constraintHint?: string): boolean {
  const pg = asPgError(error);
  if (pg.code !== "23505") return false;
  if (!constraintHint) return true;
  return `${pg.message ?? ""}${pg.details ?? ""}`.includes(constraintHint);
}
